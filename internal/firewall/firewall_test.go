// TestRenderClosesInputExceptTheKnownPorts catches a ruleset that leaves the host
// reachable on anything but loopback, ICMP, SSH, 443 and the listed ports.
func TestRenderClosesInputExceptTheKnownPorts(t *testing.T) {
	got, err := Render(Config{
		SSHPort:   2222,
		ManageSSH: true,
		Allow: []Rule{
			{Proto: "udp", Port: 51820, Comment: "wireguard"},
			{Proto: "tcp", Port: 8080},
		},
	})
	if err != nil {
		t.Fatalf("Render: %v", err)
	}
	want := `# Generated by 3x-ui. Replaces only table inet xui; other tables are untouched.
table inet xui
delete table inet xui
table inet xui {
    chain input {
        type filter hook input priority filter; policy drop;
        iifname "lo" accept
        ct state established,related accept
        meta l4proto { icmp, ipv6-icmp } accept
        tcp dport 2222 accept comment "ssh"
        tcp dport 443 accept comment "https"
        tcp dport 8080 accept
        udp dport 51820 accept comment "wireguard"
        drop
    }
}
`
	if got != want {
		t.Fatalf("rendered ruleset differs from the closed policy:\n--- got ---\n%s\n--- want ---\n%s", got, want)
	}
}

// TestRenderOnlyReplacesItsOwnTable catches a lush ruleset, which deletes
// Docker's and iptables-nft's tables and breaks their networking on every apply.
func TestRenderOnlyReplacesItsOwnTable(t *testing.T) {
	got, err := Render(Config{SSHPort: 22, ManageSSH: true})
	if err != nil {
		t.Fatalf("Render: %v", err)
	}
	for _, forbidden := range []string{"flush ruleset", "flush table"} {
		if strings.Contains(got, forbidden) {
			t.Fatalf("ruleset contains %q, which wipes tables the panel does not own:\n%s", forbidden, got)
		}
	}
	for _, required := range []string{
		"table " + TableFamily + " " + TableName,
		"delete table " + TableFamily + " " + TableName,
		"table " + TableFamily + " " + TableName + " {",
	} {
		if !strings.Contains(got, required) {
			t.Fatalf("ruleset is missing %q, so it is not an atomic replacement of the panel's own table:\n%s", required, got)
		}
	}
}

