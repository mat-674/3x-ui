// TestRenderRejectsValuesThatCouldInjectRules catches a value reaching the file
// verbatim: nft reads it line by line, so a stray quote or newline becomes a rule.
func TestRenderRejectsValuesThatCouldInjectRules(t *testing.T) {
	valid := func() Config {
		return Config{SSHPort: 22, ManageSSH: true}
	}
	cases := []struct {
		name   string
		mutate func(*Config)
	}{
		{"ssh port zero", func(c *Config) { c.SSHPort = 0 }},
		{"ssh port negative", func(c *Config) { c.SSHPort = -1 }},
		{"ssh port above range", func(c *Config) { c.SSHPort = 70000 }},
		{"allow port zero", func(c *Config) { c.Allow = []Rule{{Proto: "tcp", Port: 0}} }},
		{"allow port negative", func(c *Config) { c.Allow = []Rule{{Proto: "udp", Port: -1}} }},
		{"allow port above range", func(c *Config) { c.Allow = []Rule{{Proto: "tcp", Port: 70000}} }},
		{"unknown protocol", func(c *Config) { c.Allow = []Rule{{Proto: "sctp", Port: 80}} }},
		{"empty protocol", func(c *Config) { c.Allow = []Rule{{Proto: "", Port: 80}} }},
		{"protocol carrying a rule", func(c *Config) { c.Allow = []Rule{{Proto: "tcp accept; drop", Port: 80}} }},
		{"comment with a quote", func(c *Config) {
			c.Allow = []Rule{{Proto: "tcp", Port: 80, Comment: `x" accept`}}
		}},
		{"comment with a newline", func(c *Config) {
			c.Allow = []Rule{{Proto: "tcp", Port: 80, Comment: "x\n flush ruleset"}}
		}},
		{"comment with a semicolon", func(c *Config) {
			c.Allow = []Rule{{Proto: "tcp", Port: 80, Comment: "x; drop"}}
		}},
		{"comment with a brace", func(c *Config) { c.Allow = []Rule{{Proto: "tcp", Port: 80, Comment: "x }"}} }},
		{"comment with a control character", func(c *Config) {
			c.Allow = []Rule{{Proto: "tcp", Port: 80, Comment: "x\x00y"}}
		}},
		{"comment of 200 bytes", func(c *Config) {
			c.Allow = []Rule{{Proto: "tcp", Port: 80, Comment: strings.Repeat("a", 200)}}
		}},
	}
	for _, tc := range cases {
		t.Run(tc.name, func(t *testing.T) {
			cfg := valid()
			tc.mutate(&cfg)
			got, err := Render(cfg)
			if err == nil {
				t.Fatalf("Render accepted an unsafe value:\n%s", got)
			}
			if got != "" {
				t.Fatalf("Render returned a ruleset with an unsafe value in it:\n%s", got)
			}
		})
	}
}

// TestRenderNeverEmitsTheSamePortTwice catches a ruleset that repeats an accept
// because a caller listed it again or because SSH sits on 443: duplicates make
// `nft list ruleset` unreadable exactly where an operator audits it by hand.
func TestRenderNeverEmitsTheSamePortTwice(t *testing.T) {
	cases := []struct {
		name string
		cfg  Config
	}{
		{"ssh on xray's port", Config{SSHPort: HTTPSPort, ManageSSH: true}},
		{"https listed again", Config{
			SSHPort: 22, ManageSSH: true,
			Allow: []Rule{{Proto: "tcp", Port: HTTPSPort}, {Proto: "tcp", Port: 22}},
		}},
		{"the same extra port twice", Config{
			SSHPort: 22, ManageSSH: true,
			Allow: []Rule{{Proto: "udp", Port: 51820}, {Proto: "udp", Port: 51820}},
		}},
	}
	for _, tc := range cases {
		t.Run(tc.name, func(t *testing.T) {
			got, err := Render(tc.cfg)
			if err != nil {
				t.Fatalf("Render: %v", err)
			}
			seen := map[string]struct{}{}
			for _, line := range strings.Split(got, "\n") {
				fields := strings.Fields(line)
				if len(fields) < 4 || fields[1] != "dport" {
					continue
				}
				key := fields[0] + "/" + fields[2]
				if _, dup := seen[key]; dup {
					t.Fatalf("%s is accepted twice:\n%s", key, got)
				}
				seen[key] = struct{}{}
			}
			if len(seen) == 0 {
				t.Fatalf("the ruleset accepts no port at all:\n%s", got)
			}
		})
	}
}

// TestRenderRefusesADropPolicyThatWouldCloseSSH catches the lockout: a drop policy
// without an SSH accept closes the port the operator is connected through.
func TestRenderRefusesADropPolicyThatWouldCloseSSH(t *testing.T) {
	got, err := Render(Config{SSHPort: 2222, ManageSSH: false})
	if !errors.Is(err, ErrSSHUnmanaged) {
		t.Fatalf("Render with ManageSSH=false returned %v, want ErrSSHUnmanaged", err)
	}
	if got != "" {
		t.Fatalf("Render returned a ruleset it should have refused:\n%s", got)
	}
}
