// Package firewall renders the nftables ruleset the panel installs on its host.
// It is a pure renderer: nothing here touches a live firewall.
package firewall

import (
	"errors"
	"fmt"
	"sort"
	"strconv"
	"strings"
	"unicode/utf8"
)

// TableName is the panel's own nftables table. The ruleset replaces this table
// and nothing else, so Docker's and iptables-nft's tables keep working.
const (
	TableFamily = "inet"
	TableName   = "xui"
	// TableRef is how nft prints the table in `nft list ruleset` / `nft list tables`.
	TableRef = TableFamily + " " + TableName
	// HTTPSPort is Xray's REALITY inbound: the one public TCP port of the deployment.
	HTTPSPort = 443
	// maxCommentLen stays well below the kernel's 128-byte rule comment limit.
	maxCommentLen = 96
)

// ErrSSHUnmanaged reports a config whose default-drop policy would close SSH,
// the one port a remote operator has no way back through.
var ErrSSHUnmanaged = errors.New("firewall: default-drop policy without an SSH accept would lock the operator out")

// Rule is one extra port to open beyond SSH and 443.
type Rule struct {
	// Proto is "tcp" or "udp".
	Proto string
	Port  int
	// Comment is an optional nft rule comment, shown by `nft list ruleset`.
	Comment string
}

// Config is the desired input policy for the host.
type Config struct {
	// SSHPort is the port sshd listens on. It is required when ManageSSH is set.
	SSHPort int
	// Allow are the extra ports open besides SSH and 443/tcp.
	Allow []Rule
	// ManageSSH decides whether the panel keeps SSH reachable. Without it the
	// ruleset would drop SSH, so rendering is refused rather than guessed.
	ManageSSH bool
}

// Render produces the complete nftables ruleset.
func Render(cfg Config) (string, error) {
	sshPort, allow, err := cfg.prepare()
	if err != nil {
		return "", err
	}

	var b strings.Builder
	w := func(format string, args ...any) {
		fmt.Fprintf(&b, format+"\n", args...)
	}
	// The table/delete pair replaces this table atomically; `flush ruleset` would
	// delete tables the panel does not own (Docker, iptables-nft, firewalld).
	w("# Generated by 3x-ui. Replaces only table %s; other tables are untouched.", TableRef)
	w("table %s", TableRef)
	w("delete table %s", TableRef)
	w("table %s {", TableRef)
	w("    chain input {")
	w("        type filter hook input priority filter; policy drop;")
	w(`        iifname "lo" accept`)
	w("        ct state established,related accept")
	w("        meta l4proto { icmp, ipv6-icmp } accept")
	if sshPort != HTTPSPort {
		w(`        tcp dport %d accept comment "ssh"`, sshPort)
	}
	w(`        tcp dport %d accept comment "https"`, HTTPSPort)
	for _, r := range allow {
		if r.Comment == "" {
			w("        %s dport %d accept", r.Proto, r.Port)
			continue
		}
		w(`        %s dport %d accept comment "%s"`, r.Proto, r.Port, r.Comment)
	}
	w("        drop")
	w("    }")
	w("}")
	return b.String(), nil
}

// prepare validates every value that reaches the file and returns the rules to
// open, deduplicated and ordered so two identical configs render the same text.
func (c Config) prepare() (int, []Rule, error) {
	if !c.ManageSSH {
		return 0, nil, ErrSSHUnmanaged
	}
	if err := validatePort(c.SSHPort); err != nil {
		return 0, nil, fmt.Errorf("firewall: ssh port: %w", err)
	}
	seen := map[string]struct{}{portKey("tcp", c.SSHPort): {}, portKey("tcp", HTTPSPort): {}}
	allow := make([]Rule, 0, len(c.Allow))
	for _, r := range c.Allow {
		proto, err := normalizeProto(r.Proto)
		if err != nil {
			return 0, nil, err
		}
		if err := validatePort(r.Port); err != nil {
			return 0, nil, fmt.Errorf("firewall: allow rule: %w", err)
		}
		if err := validateComment(r.Comment); err != nil {
			return 0, nil, err
		}
		key := portKey(proto, r.Port)
		if _, dup := seen[key]; dup {
			continue
		}
		seen[key] = struct{}{}
		allow = append(allow, Rule{Proto: proto, Port: r.Port, Comment: r.Comment})
	}
	sort.SliceStable(allow, func(i, j int) bool {
		if allow[i].Proto != allow[j].Proto {
			return allow[i].Proto < allow[j].Proto
		}
		return allow[i].Port < allow[j].Port
	})
	return c.SSHPort, allow, nil
}

func portKey(proto string, port int) string {
	return proto + "/" + strconv.Itoa(port)
}

func validatePort(port int) error {
	if port < 1 || port > 65535 {
		return fmt.Errorf("port %d out of range 1-65535", port)
	}
	return nil
}

func normalizeProto(proto string) (string, error) {
	switch p := strings.ToLower(strings.TrimSpace(proto)); p {
	case "tcp", "udp":
		return p, nil
	default:
		return "", fmt.Errorf("firewall: protocol %q is not tcp or udp", proto)
	}
}

// validateComment keeps an nft comment from ending its quoting or its line: nft
// reads the file as commands, so a stray quote or newline would become rules.
func validateComment(comment string) error {
	if comment == "" {
		return nil
	}
	if !utf8.ValidString(comment) {
		return fmt.Errorf("firewall: comment is not valid UTF-8")
	}
	if len(comment) > maxCommentLen {
		return fmt.Errorf("firewall: comment %q is longer than %d bytes", comment, maxCommentLen)
	}
	for _, r := range comment {
		if r < 0x20 || r == 0x7f {
			return fmt.Errorf("firewall: comment %q contains a control character", comment)
		}
		if strings.ContainsRune("\"\\{};$`", r) {
			return fmt.Errorf("firewall: comment %q contains %q, which nft would read as syntax", comment, r)
		}
	}
	return nil
}
