// Package edge runs the nginx perimeter that sits behind Xray's REALITY
// fallback: it terminates TLS with the real certificate and serves the decoy
// site, the panel and the subscription on loopback.
package edge

import (
	"fmt"
	"net"
	"path/filepath"
	"strconv"
	"strings"
)

// Config is the desired nginx state. It is derived from panel settings and
// rendered into a complete config file, so the running perimeter never depends
// on whatever happens to be in /etc/nginx.
type Config struct {
	// Listen is the loopback address Xray's REALITY dest points at.
	Listen string
	Port   int

	// ProxyProtocol must match the inbound's `xver`: with it on, nginx reads the
	// client address from the PROXY header Xray prepends.
	ProxyProtocol bool

	ServerNames []string
	CertFile    string
	KeyFile     string

	// DecoyRoot holds the uploaded site. NotFoundFile is the page served for
	// every path the site does not define, so a probe never sees an nginx error.
	DecoyRoot    string
	DecoyIndex   string
	NotFoundFile string

	// PanelPrefix is the secret base path the panel is served under.
	PanelPrefix   string
	PanelUpstream string

	// SubPrefixes are the subscription's secret paths, each proxied to SubUpstream.
	SubPrefixes []string
	SubUpstream string

	// PidFile, LogDir and TempDir live inside the generated state directory.
	PidFile string
	LogDir  string
	TempDir string

	// HTTPPort is the public plaintext port: ACME validation plus the redirect to
	// HTTPS. 0 disables the block, which leaves a host that has no port 80.
	HTTPPort int
	// HTTPListen is its bind address; "" binds every interface.
	HTTPListen string
	// AcmeRoot is the webroot that /.well-known/acme-challenge/ is served from.
	AcmeRoot string
}

// Render produces the full nginx configuration. Everything that reaches a client
// is deliberate: no version banner, no nginx default error page, no directory
// listing, and one neutral 404 for every path the site does not define.
func Render(cfg Config) (string, error) {
	if err := cfg.validate(); err != nil {
		return "", err
	}

	var b strings.Builder
	w := func(format string, args ...any) {
		fmt.Fprintf(&b, format+"\n", args...)
	}

	w("# Generated by 3x-ui. Edits are overwritten on every reload.")
	w("worker_processes auto;")
	w("error_log %s warn;", filepath.Join(cfg.LogDir, "error.log"))
	w("pid %s;", cfg.PidFile)
	w("")
	w("events {")
	w("    worker_connections 1024;")
	w("}")
	w("")
	w("http {")
	w("    # A version banner in every response is a free hint for a scanner.")
	w("    server_tokens off;")
	w("    default_type application/octet-stream;")
	w("    access_log %s;", filepath.Join(cfg.LogDir, "access.log"))
	w("    client_body_temp_path %s/client_body;", cfg.TempDir)
	w("    proxy_temp_path %s/proxy;", cfg.TempDir)
	w("    fastcgi_temp_path %s/fastcgi;", cfg.TempDir)
	w("    uwsgi_temp_path %s/uwsgi;", cfg.TempDir)
	w("    scgi_temp_path %s/scgi;", cfg.TempDir)
	w("")
	w("    server {")
	w("        listen %s;", cfg.listenLine())
	w("        server_name %s;", strings.Join(cfg.ServerNames, " "))
	w("")
	w("        ssl_certificate %s;", cfg.CertFile)
	w("        ssl_certificate_key %s;", cfg.KeyFile)
	w("        ssl_protocols TLSv1.2 TLSv1.3;")
	w("        ssl_prefer_server_ciphers off;")
	w("        ssl_session_cache shared:XUI:10m;")
	w("        ssl_session_timeout 1d;")
	if cfg.ProxyProtocol {
		w("")
		// Xray is the only writer of the PROXY header, and it dials from loopback.
		w("        set_real_ip_from 127.0.0.1;")
		w("        set_real_ip_from ::1;")
		w("        real_ip_header proxy_protocol;")
	}
	w("")
	w("        root %s;", cfg.DecoyRoot)
	w("        index %s;", cfg.DecoyIndex)
	w("")
	w("        # Every path the site does not define looks like the site's own 404.")
	w("        error_page 404 /404.html;")
	w("        location = /404.html {")
	w("            internal;")
	w("            root %s;", filepath.Dir(cfg.NotFoundFile))
	w("        }")
	w("")
	w("        location %s {", cfg.PanelPrefix)
	writeProxy(&b, "            ", cfg.PanelUpstream, true)
	w("        }")
	for _, prefix := range cfg.SubPrefixes {
		w("")
		w("        location %s {", prefix)
		writeProxy(&b, "            ", cfg.SubUpstream, false)
		w("        }")
	}
	w("")
	w("        location / {")
	w("            try_files $uri $uri/ =404;")
	w("        }")
	w("    }")

	if cfg.HTTPPort > 0 {
		w("")
		// A real site answers on 80 and redirects; a host where 80 is silent is
		// itself a signal. The challenge path is served before the redirect so a
		// renewal never needs the firewall touched.
		w("    server {")
		w("        listen %s;", cfg.httpListenLine())
		w("        server_name %s;", strings.Join(cfg.ServerNames, " "))
		w("        server_tokens off;")
		w("")
		w("        location ^~ /.well-known/acme-challenge/ {")
		w("            root %s;", cfg.AcmeRoot)
		w("            default_type text/plain;")
		w("        }")
		w("")
		w("        location / {")
		w("            return 301 https://$host$request_uri;")
		w("        }")
		w("    }")
	}
	w("}")

	return b.String(), nil
}

// writeProxy emits a reverse-proxy block at the given indent. The panel needs the
// WebSocket upgrade and a trusted client address; the subscription needs only
// the address and scheme.
func writeProxy(b *strings.Builder, indent, upstream string, panel bool) {
	line := func(format string, args ...any) {
		fmt.Fprintf(b, indent+format+"\n", args...)
	}
	line("proxy_pass http://%s;", upstream)
	line("proxy_http_version 1.1;")
	line("proxy_set_header Host $host;")
	line("proxy_set_header X-Forwarded-Proto https;")
	// Overwritten, never appended: the panel trusts loopback and would otherwise
	// believe a client-supplied X-Forwarded-For.
	line("proxy_set_header X-Forwarded-For $remote_addr;")
	line("proxy_set_header X-Real-IP $remote_addr;")
	if panel {
		line("proxy_set_header Upgrade $http_upgrade;")
		line("proxy_set_header Connection \"upgrade\";")
		line("proxy_read_timeout 1h;")
	}
}

func (c Config) listenLine() string {
	line := net.JoinHostPort(c.Listen, strconv.Itoa(c.Port)) + " ssl http2"
	if c.ProxyProtocol {
		line += " proxy_protocol"
	}
	return line
}

// httpListenLine renders the plaintext listener: a bare port binds every
// interface, which is what a public site needs.
func (c Config) httpListenLine() string {
	listen := strings.TrimSpace(c.HTTPListen)
	switch listen {
	case "", "0.0.0.0":
		return strconv.Itoa(c.HTTPPort)
	}
	return net.JoinHostPort(listen, strconv.Itoa(c.HTTPPort))
}

func (c Config) validate() error {
	switch {
	case c.Port <= 0 || c.Port > 65535:
		return fmt.Errorf("edge: port %d out of range", c.Port)
	case c.Listen == "":
		return fmt.Errorf("edge: listen address is required")
	case len(c.ServerNames) == 0:
		return fmt.Errorf("edge: at least one server name is required")
	case c.CertFile == "" || c.KeyFile == "":
		return fmt.Errorf("edge: certificate and key paths are required")
	case c.DecoyRoot == "":
		return fmt.Errorf("edge: decoy root is required")
	case c.NotFoundFile == "":
		return fmt.Errorf("edge: not-found page is required")
	case c.PanelUpstream == "":
		return fmt.Errorf("edge: panel upstream is required")
	case !validPrefix(c.PanelPrefix):
		return fmt.Errorf("edge: panel prefix %q is not an absolute path", c.PanelPrefix)
	}
	if c.HTTPPort != 0 {
		if c.HTTPPort < 0 || c.HTTPPort > 65535 {
			return fmt.Errorf("edge: http port %d out of range", c.HTTPPort)
		}
		if c.HTTPPort == c.Port {
			return fmt.Errorf("edge: the plaintext and TLS ports cannot both be %d", c.Port)
		}
		if strings.TrimSpace(c.AcmeRoot) == "" {
			return fmt.Errorf("edge: an ACME webroot is required when port %d is served", c.HTTPPort)
		}
	}
	for _, p := range c.SubPrefixes {
		if !validPrefix(p) {
			return fmt.Errorf("edge: subscription prefix %q is not an absolute path", p)
		}
	}
	return nil
}

// validPrefix reports whether p can be used as an nginx location prefix: it must
// start with "/" and carry no whitespace or directive-breaking characters.
func validPrefix(p string) bool {
	if !strings.HasPrefix(p, "/") {
		return false
	}
	return !strings.ContainsAny(p, " \t\r\n{};\"'")
}
